/// 服務版本 —— **內部編號**,只用來分辨手上這支執行檔是哪一版。
///
/// 沿革:
///
/// | 版本 | 改了什麼 |
/// |---|---|
/// | `0.0.0.1` | 最初版:心率 / 血氧 / HRV / 波形 / 晶片控制 |
/// | `0.0.0.2` | 新增 `strapi` 區塊(整合方介面形狀的欄位) |
/// | `0.0.0.3` | `strapi` 區塊的公式、單位與 confidence 對齊 `aquivio-vitals` |
/// | `0.0.0.4` | SNR 頻帶定義補齊(**`snr_db` 數值變動**);兩套判讀加上 `_video` / `_max30102` 後綴 |
///
/// ⚠️ **`0.0.0.3` → `0.0.0.4` 是行為變更,不只是欄位改名。**
///    SNR 的頻帶定義補齊之後,同一份訊號算出來的 `snr_db` 會**變大**
///    0.35~5.10 dB(實測 13 份快照),`confidence` 也可能從 `rough` 變 `good`。
///    若下游已依 `0.0.0.3` 的數值調過門檻,升版後要重新確認。
