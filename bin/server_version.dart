/// 服務版本 —— **內部編號**,只用來分辨手上這支執行檔是哪一版。
///
/// 沿革:
///
/// | 版本 | 改了什麼 |
/// |---|---|
/// | `0.0.0.1` | 最初版:心率 / 血氧 / HRV / 波形 / 晶片控制 |
/// | `0.0.0.2` | 新增 `strapi` 區塊(整合方介面形狀的欄位) |
/// | `0.0.0.3` | `strapi` 區塊的公式、單位與 confidence 對齊 `aquivio-vitals` |
/// | `0.0.0.4` | SNR 頻帶定義補齊(**`snr_db` 數值變動**);新增 `confidence_video` 別名 |
/// | `0.0.0.5` | WS `/stream` 加推 `wave` 區塊(IR 截尾平滑的增量波形) |
/// | `0.0.0.6` | RED/IR 通道方向自動判定(**行為變更**);新增 `channelOrient` |
/// | `0.0.0.7` | `confidence` 改看脈搏(SQI + 拍數 + RR 空洞),只剩 `good` / `very rough`(**數值變動**);WS `wave` 改由核心輸出 = 找谷用的線(批尾截斷修正、補上低通) |
///
/// ## ⚠️ `0.0.0.7`:`confidence` 不再看頻譜
///
/// 站台拿 `confidence` 當把關(`very rough` / `null` 就不去要推薦)。原本照攝影機
/// 的 `hrv_confidence()` 看 SNR,但那是攝影機訊號弱、要先確認「有沒有脈搏」才需要的;
/// 手指感測的脈搏本來就強,頻譜反而會把心率自然的起伏算成雜訊。
///
/// | 欄位 | `0.0.0.6` | `0.0.0.7` |
/// |---|---|---|
/// | `confidence` | SNR 三級 / 算不出來給 `null` | 異常(RR 空洞數 + SQI 沒過)≤ 1 次 且 拍數 ≥ 9 + 空洞數 → `good`,其他(含手指離開)→ `very rough` |
/// | `confidence_video` | 與 `confidence` 同值 | **維持 SNR 三級**,兩者不再相同 |
/// | `snr_db` / `confidence_by_beats` | — | 不變 |
///
/// 空洞 = 相鄰兩拍接不起來(有一拍沒通過考驗、補漏拍也沒補回)。掉的拍已剔除、不進 HRV,
/// 所以容許 1 次異常;一開始是零容忍,實測連單純漏一拍(其餘拍都乾淨)也被判 very rough,
/// 才放寬。只看 SQI 不夠:照木頭時 SQI 照樣過關(心率 150、血氧 99.9),但有 3 個空洞。
///
/// ### 同一版:WS `/stream` 的 `wave` / `raw_wave` 改由核心輸出
///
/// 截尾平滑是置中濾波(第 i 筆要用 i+1 ~ i+4)。0.0.0.6 的 server 拿核心逐批給的
/// `newIrTrim` 去減 baseline —— 那是每批一到就算的,**批尾 4 筆右側截斷**,交出去就凍住,
/// server 的 1 秒延遲只修到 baseline。站台照著畫,每批(約 0.1 秒)一個小缺口。
///
/// 現在核心輸出 `newIrWave` 與 `newIrWaveTrim`,等右邊 110 筆(截尾半窗 4 +
/// baseline 半窗 100 + 低通半窗 6)到齊才給;server 原封轉送,不再自己延遲、自己算。
/// `wave` 的內容 = **核心找谷用的那條線**(`Max30102Signal.troughLine`:截尾 → 減 baseline
/// → 低通)。0.0.0.6 少了最後的低通,畫出來的線比找谷用的線毛一點,谷點不一定落在線的低點。
/// 欄位名稱與格式不變,站台不用改。另外兩個差異:量測一開始那 1 秒的左邊也完整了
/// (核心緩衝裡有沉澱期當前後文);`GET /waveform` 的 `irTrim` / `redTrim` 改成回應當下
/// 對整段重算(只剩陣列最後 4 筆沒有右邊資料)。
///
/// ⚠️ 這一版開發中先以「只看 SQI」的內容 push 過一次(`f3ac733`),版本字串同為
/// `0.0.0.7`。那支只在開發機台測試過、**沒有交付**;交付的 `0.0.0.7` 以加上
/// 拍數與空洞的這版為準。
///
/// ## ⚠️ `0.0.0.6` 是行為變更,不只是加欄位
///
/// 起因:實測 8 片 MAX30102 模組,其中 7 片**把兩顆 LED 晶粒裝反**(今華電子那批;
/// 廣鏵那片正常)。datasheet 規定 `0x0C` = LED1 = 紅光、FIFO 順序 RED 在前,
/// 我們的解碼完全照規格 —— 但那種模組送出來的兩路是對調的,血氧會算成
/// 生理上不可能的值(R = 2.35 → 血氧 −83%),然後被範圍檢查擋掉變成 `null`。
///
/// 核心現在每次量測**自己判定一次方向**(靠 AC/DC 比值,不能靠讀數大小),
/// 判定完成後把輸出轉正。三個對下游可見的變化:
///
/// | 變化 | 影響 |
/// |---|---|
/// | 方向判定完成前**不輸出波形樣本** | `/waveform` 與 WS `wave` 比以前晚約 2 秒才有第一筆 |
/// | 血氧要等方向確定才給 | `spo2` 在最初幾秒是 `null`(心率不受影響,照常) |
/// | 對調的模組輸出會被轉正 | `ir` / `red` 兩路的內容與 `0.0.0.5` 相反 |
///
/// 判別模組是不是裝反的:送 `40 71 31 09 01 0D 00 00 07` 關掉 `0x0D`
/// (datasheet 說那是紅外),**紅光消失就是裝反的**。復原用 RE-INIT。
/// 完整的查證過程寫在 `docs/SERVER_GUIDE.*.md` 最下方。
///
/// `0.0.0.5` 是**純新增**:既有欄位一個都沒動,數值也沒動,舊的訂閱者忽略
/// `wave` 就跟 `0.0.0.4` 完全一樣。之所以還是升版,是因為版本號要回答的問題是
/// 「我手上這支**做得到什麼**」—— 整合方問「你們的 WS 有推波形嗎」時,
/// `--version` 要答得出來。這正是 `0.0.0.3` 兩個 build 那次的教訓。
///
/// ⚠️ **`0.0.0.3` → `0.0.0.4` 是行為變更,不只是欄位改名。**
///    SNR 的頻帶定義補齊之後,同一份訊號算出來的 `snr_db` 會**變大**
///    0.35~5.10 dB(實測 13 份快照),`confidence` 也可能從 `rough` 變 `good`。
///    若下游已依 `0.0.0.3` 的數值調過門檻,升版後要重新確認。
///
/// ## ⚠️⚠️ `0.0.0.3` 有兩個不同的 build,版本字串一樣
///
/// | commit | 日期 | `snr_db` 的頻帶 | 流向 |
/// |---|---|---|---|
/// | `8ec45ce` | 2026-09-04 | 舊定義(f0±0.1 / 雜訊 0.5~5.0 Hz)→ 偏低 | **交付給整合方的就是這版** |
/// | `49f42e8` | 2026-09-07 | 新定義(f0±0.2 / 雜訊 0.5~4.0 Hz)→ 偏高 | 只有 CI 產物,未交付 |
///
/// `49f42e8` 改了 SNR 的頻帶(輸出行為變了)卻**忘了同步升版號**,所以兩個
/// 行為不同的執行檔都回報 `0.0.0.3` —— **`--version` 分不出來**。
///
/// 這正是版本號要防的事,結果第一次就踩到。教訓寫在這裡:
/// **只要改到會影響 `/vitals` 輸出的東西,同一個 commit 就要動這個檔。**
///
/// 手上若有自稱 `0.0.0.3` 的執行檔,**一律當成 `8ec45ce` 那版**(偏嚴),
