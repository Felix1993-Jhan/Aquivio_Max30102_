// ============================================================================
// Max30102Config (K2 交接版) — 精簡後的可調參數
// ============================================================================
// 與原版差異(交接考量):
//   · 只留「真的需要外部調」的項目,其餘固定成常數 → 降低誤用風險。
//   · 移除「輪詢間隔」:K2 不自己收串口,計時由軟體那邊決定。
//   · 移除「更新間隔(ms)」:改成「累積筆數 computeEvery」(見 k2_core)。
//   · 截尾視窗 / SpO2 上下限 / 血氧公式 → 固定不開放。
//
// ★ 重點①:HR(bpm) 與 濾波(Hz) 是「同一件事的兩種單位」(Hz = bpm / 60)。
//    舊版分兩組欄位各自設 → 會脫鉤。這裡改成**單一來源**:存 hrMin/hrMax(bpm),
//    bandLowHz/bandHighHz 自動換算;用哪一邊設定都會連動,永遠一致。
//
// ★ 重點②:平滑係數(spo2SmoothFactor / hrSmoothFactor)**K2 核心不套用**,
//    只是提供給「呈現層(UI / 軟體)」參考 —— 核心一律吐原始值,平滑是 UI 的事。
// ============================================================================

class Max30102Config {
  // ── 固定項(不開放調整)────────────────────────────────────────────
  /// 取樣率(Hz)。韌體設定;改它要同步檢視演算法。
  static const int samplingRateHz = 100;

  /// 截尾視窗(筆):去突波用,固定。
  static const int trimWindow = 9;

  /// SpO2 合理範圍(固定)。
  static const int spo2Min = 70;
  static const int spo2Max = 100;

  /// 血氧公式:false = 二次多項式(Maxim);固定。
  static const bool spo2Linear = false;

  /// **演算視窗(筆)** = 每次計算取「最新 N 筆」。500 = 5 秒 @100Hz。**固定不開放調。**
  ///
  /// 為什麼固定:
  ///   · 視窗變長**不會讓演算法更準** —— 谷是局部極小、R 是逐拍算的,兩者都不吃長視窗;
  ///     唯一的影響是 SQI / cv 這些整窗統計變遲鈍(要更久才反映出體動)。
  ///   · 視窗變短則直接壞:< 100 筆時「不足 1 秒」保護永遠成立 → 完全沒有輸出;
  ///     300 筆以下慢心率湊不到 3 顆谷,`_computeMaxim` 也會回空。
  ///   · 它還牽動起步階段的左緣 context 判斷([Max30102K2] 的 `outputFrom`)。
  /// 500 對 30~240bpm 全區間都夠(約 6~7 拍),沒有調整的理由,鎖起來少一個誤用面。
  static const int computeWindow = 500;

  // ── 通道方向自動判定(RED / IR 誰是誰)────────────────────────────────
  //
  // 為什麼需要:市面上有 MAX30102 模組**把兩顆 LED 晶粒裝反**(見專案文件的
  // 「已知硬體問題」)。datasheet 規定 `0x0C` = LED1 = 紅光、FIFO 順序 RED 在前,
  // 我們的解碼完全照規格,但那種模組送出來的兩路是對調的。
  //
  // 為什麼不能靠讀數大小判斷:DC 高低只反映「LED 多亮、光路耦合多好」,
  // 每片都不同,實測兩片健康板的方向還相反。**有識別資訊的只有 AC/DC 比值** ——
  // 也就是血氧的 R,除以 DC 正好把硬體差異消掉,剩下波長的物理特性。
  //
  // 判定規則(R = 逐拍 (AC/DC)red ÷ (AC/DC)ir,由演算層算好):
  //   R < [orientRatioNormal]   → 目前的假設是對的
  //   R > [orientRatioSwapped]  → 目前的假設是反的
  //   兩者之間                   → **不判定**,這一輪不投票也不給血氧
  //
  // 決策邊界在 **R = 1**(血氧約 80%)—— 那裡 R 與 1/R 相等,兩個方向的
  // 解釋一樣合理。模糊帶就圍著它開,兩側各留一段。

  /// R 低於此值 → 判定「目前假設正確」。
  ///
  /// 0.9 換算血氧約 87%。門檻不能再往下壓:`R = 0.7` 已經是血氧 94%,
  /// 那是**正常讀數**,壓到那裡會讓健康的人被判成「分不出來」而拿不到血氧。
  static const double orientRatioNormal = 0.9;

  /// R 高於此值 → 判定「目前假設相反」。
  ///
  /// 1.3 換算血氧約 55%。**中間那段(0.9~1.3)刻意不判定** —— 那正好是
  /// 「真的缺氧」與「通道接反」分不開的區域:同一個 R,兩種解釋都說得通。
  /// 分不出來就不猜:寧可不給血氧,也不要把危險值自動改寫成正常值。
  ///
  /// 實測值離模糊帶都很遠:正常板 0.46、對調板 2.35(對調後 0.42)。
  static const double orientRatioSwapped = 1.3;

  /// 連續幾輪判定一致才鎖定方向。
  ///
  /// 演算法約每秒算一次,R 從第 3 顆谷(約 3 秒)開始就有,而且很穩
  /// (實測 3s→8s 只飄 2%)。2 票擋得住單次異常,又只多等 1 秒。
  static const int orientVotesToLatch = 2;

  /// 沉澱結束後多久還沒鎖定 → 放棄判定,退回 datasheet 預設方向。
  ///
  /// **逃生口,不是正常路徑。** 沒有它的話,訊號差到湊不出 3 顆谷的人
  /// 會連波形都看不到(方向未定時不輸出樣本)。逾時後波形照給、心率照給,
  /// 但血氧仍然不給 —— 方向沒確定就沒有可信的血氧。
  static const int orientTimeoutMs = 10000;

  /// [orientTimeoutMs] 換算成筆數。
  static int get orientTimeoutSamples => orientTimeoutMs * samplingRateHz ~/ 1000;

  /// NN 序列**硬上限(拍)** —— 純記憶體保險,不是主要界線。
  /// 真正的界線是 [dataHistoryMs](時間)。拍數表達不了時間:300 拍在 40bpm 是
  /// 7.5 分鐘、在 120bpm 只有 2.5 分鐘,同一個數字意義完全不同。
  static const int maxBeats = 300;

  /// computeEvery 下限 = 一次詢問(100ms @100Hz)的量 = 10 筆。
  static const int minComputeEvery = 10;

  // ── 開放調整 ──────────────────────────────────────────────────────
  // ⚠️ 核心目前**不驗證**這些值。填錯不會報錯,而是「安靜地壞掉」——
  //    各參數的誤設後果寫在自己的註解裡,調之前請先看。

  /// 手指偵測門檻(IR 平均 ≥ 此值視為有手指)。
  ///
  /// 單位與 [HrSpo2Result.irDc] 相同 —— 想調門檻就先看那個實際讀數。
  /// IR 是 18-bit,值域 0~262143;**設超過 262143 就永遠偵測不到手指**(畫面全空)。
  int fingerThreshold;

  /// 谷顯著度門檻 = promRatio × 第 70 百分位。越小越容易收進較矮的谷。
  ///
  /// ⚠️ 設 0 或負數 → 門檻歸零,雜訊全被當成谷,心率暴衝。
  double promRatio;

  /// **目前硬體使用的 LED 驅動電流**(8-bit 暫存器值,對應 LED1_PA `0x0C` / LED2_PA `0x0D`)。
  ///
  /// ⚠️ **核心不會自動套用這個值** —— 它是「紀錄」不是「開關」。
  ///    真正要改晶片,得由軟體端送 `Max30102Protocol.buildWriteReg(reg, value)`。
  ///    放在這裡的用意是讓上層隨時知道「我們現在跑在多大的電流下」,
  ///    因為底下那些校正全部綁在這個前提上。
  ///
  /// 預設 `0x24` = 韌體 ReInit 之後晶片回到的值(見 `Max30102Protocol.kLedBaseline`)。
  ///
  /// ── 改了會連動什麼 ────────────────────────────────────────────────
  /// **不受影響**(全是比值,分子分母同時縮放會抵銷):
  ///   · [promRatio] 的顯著度門檻 · SQI 的 cv 與 spike
  ///   · 找谷 → RR → HRV 整條線(走的是去趨勢後的**相對形狀**,不看絕對位準)
  ///   → 換句話說,**心率與 HRV 對 LED 電流是穩健的**。
  ///
  /// **會受影響**:
  ///   · [fingerThreshold] —— 直接與 IR DC 比,同單位。電流拉高 DC 跟著漲,
  ///     門檻會變得太好過;調低則可能永遠達不到。**必須跟著重調。**
  ///   · **SpO2** —— 血氧多項式的係數是針對特定光學條件校出來的。改變
  ///     **紅光/紅外的電流比例**會讓 R 系統性偏移,而公式照舊算 →
  ///     血氧穩定地偏掉幾個百分點,看起來完全正常、沒有任何異常徵兆。
  ///   · **ADC 飽和** —— IR 是 18-bit(上限 262143)。電流過大會削平波峰、
  ///     破壞 AC 幅度,SpO2 直接失效(波形上看得出頂部被切平)。
  ///
  /// 所以調 LED 電流比較接近「重新校正硬體」而不是「調一個參數」。
  int ledCurrentRed;
  int ledCurrentIr;

  /// 補漏拍(search-back):預設關(寧缺勿假)。
  bool searchBackEnabled;

  /// clean(全域 MAD 離群濾):預設開。
  bool cleanEnabled;

  /// 呈現層 EMA 平滑係數 —— **核心完全不套用**,放在這裡是當作「建議值」交給軟體端。
  ///
  /// 這組數字來自先前實作採用的做法,公式是:
  /// ```
  /// 顯示值ₙ = k × 顯示值ₙ₋₁ + (1 − k) × 原始值ₙ
  ///     血氧 k = 0.7    心率 k = 0.8
  /// ```
  ///
  /// ⚠️ 套用前先知道核心**已經做過一層平滑**(但不是 EMA):
  ///   · 心率 = 最近 6 拍 RR 的**中位數** → 已涵蓋約 5 秒
  ///   · 血氧 = 視窗內逐拍 R 的**中位數**
  /// 用中位數而不用 EMA 是刻意的:中位數抗離群(一次體動不會把數字拉走),
  /// EMA 會把離群值按權重吃進去再慢慢吐出來。
  ///
  /// 所以再疊一層 EMA 是**加總延遲**:心率(中位 ≈5s + EMA 0.8 ≈4s)會明顯變鈍;
  /// 血氧變化本來就慢,加了比較沒有感覺。要不要加、加多少,由軟體端自行決定。
  ///
  /// ⚠️ 係數需落在 0~1,超出會發散 —— 核心不用它,所以壞的只有照抄的軟體。
  double spo2SmoothFactor;
  double hrSmoothFactor;

  // ── HR 上下限(bpm):**單一來源**;濾波 Hz 由它換算,永遠一致 ────────

  /// HR 下限(bpm)。
  ///
  /// ⚠️ **這個參數一改會連動三件事,不是只有「心率下限」**:
  ///
  /// | 影響到 | 換算 | hrMin=30 | hrMin=60 |
  /// |--------|------|----------|----------|
  /// | 生理閘門的 RR 上限 | `60000 / hrMin` | 2000ms | 1000ms |
  /// | 濾波下限 = **baseline 移動平均視窗寬** | `fs ÷ (hrMin/60)` | 200 筆(2秒) | **100 筆(1秒)** |
  /// | [settleSamples] 沉澱期長度(綁在 baseline 寬度上) | 同上 | 200 筆 | **100 筆** |
  ///
  /// 也就是說把 hrMin 從 30 調到 60,**baseline 視窗與沉澱期會直接砍半**。
  /// 這是刻意的連動(baseline 要擋掉比最慢心跳更慢的漂移,兩者本來就該同步),
  /// 但調參數的人很容易只想到「心率下限」而忽略後兩項 —— 調之前請先看這張表。
  ///
  /// 反過來:想要更寬的 baseline(擋更慢的呼吸漂移)→ 把 hrMin 調**低**。
  int hrMin;

  /// HR 上限(bpm)。
  ///
  /// ⚠️ 同樣連動兩件事:
  ///   · 生理閘門的 RR 下限 = `60000 / hrMax`(240 → 250ms)
  ///   · 找谷的最小間距 `minDist` = `60×fs / hrMax`(240 → 25 筆)——
  ///     調低會讓兩顆谷之間被強制拉開,快心跳可能被當成同一拍而漏抓。
  ///
  /// ⚠️ 必須 `hrMax > hrMin`。寫反(例如 30/240 填成 240/30)會讓 RR 上限小於下限,
  ///    **每一拍都同時「太長」又「太短」→ 全數剔除**:波形照跳、手指 OK、SQI OK,
  ///    但心率永遠是空的,而且不會有任何錯誤訊息。
  int hrMax;

  int _computeEvery;

  Max30102Config({
    this.fingerThreshold = 50000,
    this.hrMin = 30,
    this.hrMax = 240,
    this.promRatio = 0.5,
    int computeEvery = 100,
    this.ledCurrentRed = 0x24,
    this.ledCurrentIr = 0x24,
    this.fingerDeadMs = 1500,
    this.dataHistoryMs = 30000,
    this.fingerOffBatches = 3,
    // 預設 false:交接核心的通用行為不變,要免洗語意的專案自己開。
    this.resetOnFingerOff = false,
    this.searchBackEnabled = false,
    this.cleanEnabled = true,
    this.spo2SmoothFactor = 0.7,
    this.hrSmoothFactor = 0.8,
  }) : _computeEvery =
            computeEvery < minComputeEvery ? minComputeEvery : computeEvery;

  // ── HR(bpm) ↔ 濾波(Hz) 連動:Hz = bpm / 60 ───────────────────────
  // 只存 bpm 一份;用 Hz 設定時自動換算回 bpm → 兩者永遠一致、不會脫鉤。

  /// 濾波下限(Hz)= HR 下限 / 60(連動)。
  ///
  /// 🛡 底線保護:`hrMin` 若被設成 0(或負數),這裡會回 1bpm 而不是 0 ——
  ///    因為好幾處是拿它當**除數**(`fs / bandLowHz` 算 baseline 視窗寬、沉澱期),
  ///    回 0 會變成 `Infinity.round()` 直接丟例外把 app 帶走。
  ///    真正的範圍檢查在 k2_setting_limits;這裡只是不讓它有機會炸。
  double get bandLowHz => (hrMin < 1 ? 1 : hrMin) / 60.0;
  set bandLowHz(double hz) => hrMin = (hz * 60).round();

  /// 濾波上限(Hz)= HR 上限 / 60(連動)。同樣有除數底線保護(`minDist` 用它當除數)。
  double get bandHighHz => (hrMax < 1 ? 1 : hrMax) / 60.0;
  set bandHighHz(double hz) => hrMax = (hz * 60).round();

  /// 累積幾筆「新樣本」才算一次(≈ computeEvery / 100 秒)。
  /// 100 = 1 秒;下限 10(= 一次詢問的量),設更小沒有意義(setter 會自動夾住)。
  ///
  /// ⚠️ 上限 = [computeWindow](500)。兩次計算之間滑過的樣本若超過視窗寬,
  ///    中間那段就**從來沒有被任何視窗分析過** → 那幾拍直接消失,而且沒有任何徵兆
  ///    (心率看起來正常,只是拍數莫名偏少)。setter 會自動夾住。
  int get computeEvery => _computeEvery;
  set computeEvery(int v) => _computeEvery =
      v < minComputeEvery ? minComputeEvery : (v > computeWindow ? computeWindow : v);

  /// **沉澱期(筆)** = baseline 移動平均的視窗寬度 = `fs / bandLowHz`(預設 200 = 2 秒)。
  ///
  /// 去趨勢是「原始值 − baseline」,baseline 需要這麼寬的資料才成形。不足就開始算,
  /// 手指壓上去那一階跳(0 → ~90000)會被當成訊號,炸出比脈搏大 50 倍的假暫態。
  ///
  /// 所以綁在 baseline 寬度上而不是寫死 200 —— 改 hrMin 時會自動跟著走,不會脫鉤。
  int get settleSamples => (samplingRateHz / bandLowHz).round();

  /// **空轉期(ms)** —— 偵測到手指後,先「完全不收」這麼久的資料。
  ///
  /// 為什麼需要:[fingerThreshold] 是在手指「壓到一半」時就跨過的,IR 還會繼續
  /// 從 5 萬爬到 9 萬。那段斜坡幅度是脈搏的數十倍,一旦進緩衝會連環出事 ——
  ///   ① 去趨勢炸出巨大假暫態(整條波形被壓扁);
  ///   ② 找谷門檻(promRatio × 第70百分位)被墊高 → 整個視窗只抓到斜坡自己;
  ///   ③ 生出的假 RR 污染 ±40% 誤拍閘門的中位,之後**真拍反被判成「太短」剔除**,
  ///      序列就鎖死在 2 倍週期爬不出來(輸出穩定但完全錯誤的心率)。
  ///
  /// 時序:偵測到手指 → 空轉 [fingerDeadMs] → 累積 [settleSamples] → 開始輸出。
  /// 預設 1500ms + 2000ms ≈ **3.5 秒**後才有第一筆數值(再加左緣 context 約 1 秒才有首拍)。
  ///
  /// ⚠️ 負數等於沒有空轉期(斜坡會進緩衝);設太大則遲遲等不到開始。
  /// 💡 若使用流程是「**手指先放好、再按開始量測**」,壓下去的斜坡根本不會發生,
  ///    這裡可以調小甚至歸零 —— 它擋的是「按了才放手指」的那段爬升。
  int fingerDeadMs;

  /// [fingerDeadMs] 換算成筆數。
  int get fingerDeadSamples => fingerDeadMs * samplingRateHz ~/ 1000;

  /// **核心保留時間(ms)** —— **樣本緩衝與 RR 池共用這一個界線**,兩者對得起來。
  ///
  /// 用時間而不是筆數/拍數:
  ///   · 拍數會隨心率浮動,同一個上限在不同人身上代表不同長度;
  ///   · 樣本數與拍數是兩種單位,分開設就會脫鉤(緩衝 20 秒、RR 池 30 秒 →
  ///     波形上有拍,但那段樣本已經捲掉了,對不起來)。
  /// 有了絕對索引之後,兩邊照同一個時間裁是精確的。
  ///
  /// 預設 30 秒 = 典型單次量測長度,也是 UI 顯示視窗的最大檔。
  /// **要更長的歷史請由軟體端自行累積**(核心負責算、軟體負責存)。
  ///
  /// ⚠️ 設太小會連環出事,而且都是安靜的:
  ///   · `dataHistorySamples < computeWindow` → 演算視窗永遠喂不滿,等於偷偷縮小視窗;
  ///   · RR 池湊不到 HRV 暖機需要的 9 拍 → **HRV 永遠是 null**。
  ///     慢心率(50bpm)下 9 拍要 ~11 秒,所以別低於 15000ms。
  ///
  /// 📛 命名說明:叫 **data** 不是 **rr** —— 它同時管「樣本緩衝」與「RR 池」兩個。
  ///    取名 rrHistoryMs 會讓人以為樣本緩衝另有設定,那正是我們要避免的誤會。
  int dataHistoryMs;

  /// [dataHistoryMs] 換算成樣本筆數(= 樣本緩衝上限,也是 RR 池的時間界線)。
  int get dataHistorySamples => dataHistoryMs * samplingRateHz ~/ 1000;

  /// **手指離開去彈跳(批)** —— 連續這麼多批低於門檻才判定「真的離開」。
  ///
  /// 不做去彈跳的話,接觸稍微不穩、IR 在門檻上下擺一下,就會整組清空並重新
  /// 空轉+沉澱 3.5 秒 —— 10 秒的量測會很難完成。
  /// 去彈跳期間樣本照收(避免 `_ir` 中間出現時間斷層),確認離開時才一起清掉。
  ///
  /// ⚠️ 小於 1 等於沒有去彈跳。一批 = 一次 [Max30102K2.feedData],以 100ms 輪詢
  ///    來說 3 批 ≈ 300ms。
  int fingerOffBatches;

  /// **手指離開時連絕對索引一起歸零**(「免洗式」量測用;預設關閉)。
  ///
  /// · `true`  —— 確認手指離開時,除了清緩衝與 RR 池,連 [Max30102K2.totalSamples]
  ///              也歸 0,並在該次回傳 `K2FeedResult.didReset = true`。
  ///              **每次新量測完全從零開始**,適合一人一副免洗筷式的場景:
  ///              下一位使用者的時間軸不會接在上一位後面。
  /// · `false` —— 維持原行為:離開只清緩衝與 RR 池,**保留絕對索引繼續累加**。
  ///
  /// 兩者的**觸發時機完全相同** —— 都要先過 [fingerOffBatches] 去彈跳、確認
  /// 「真的離開」才動作。單批雜訊不會觸發歸零。
  ///
  /// ⚠️ 開啟後,軟體端自己存的座標(波形陣列、`troughAbs`、`rrPoints` 的 abs)
  ///    會在歸零那一刻全部失效。收到 `didReset == true` 就要把自己累積的東西
  ///    一併丟掉重來 —— 不丟的話,新舊兩條時間軸的索引會混在一起。
  bool resetOnFingerOff;
}
